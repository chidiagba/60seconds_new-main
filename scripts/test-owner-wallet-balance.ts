import assert from 'node:assert/strict';
import { calculateOwnerWalletBalance as balance } from '../supabase/functions/_shared/owner-wallet-balance';
const sale = (date: string, amount = 1000) => ({ amount, status: 'completed', created_at: date, metadata: { entry: 'owner_credit' } });
const payout = (date: string, amount = 1000, status = 'completed') => ({ amount, status, type: 'withdrawal', created_at: date, metadata: { entry: 'paystack_bank_settlement' } });
const old = '2026-08-30T00:00:00Z';
const now = '2026-09-05T12:15:00Z';
const later = '2026-09-06T00:00:00Z';
assert.equal(balance([sale(now)]), 1000, 'purchase is credited before settlement');
assert.equal(balance([sale(now), payout(old)]), 1000, 'unmatched historical payout cannot consume a new sale');
assert.equal(balance([payout(later, 1000, 'pending'), sale(now)]), 1000);
assert.equal(balance([payout(later), sale(now)]), 0);
assert.equal(balance([sale(now), payout(later, 400)]), 600);
assert.equal(balance([payout(later, 1000, 'failed'), sale(now)]), 1000);
assert.equal(balance([sale(now), { ...payout(later), metadata: { entry: 'paystack_bank_settlement', settlement_date: old } }]), 1000);
assert.equal(balance([sale(now), { ...payout(later, 250), metadata: { entry: 'owner_withdrawal' } }]), 750);
assert.equal(balance([{ ...sale(now), status: 'pending' }]), 0);
assert.equal(balance([sale(now), { ...sale(now), amount: -1040, metadata: { entry: 'buyer_debit' } }]), 1000);
assert.equal(balance([sale(now, 0.1), sale(now, 0.2)]), 0.3);
assert.equal(balance([payout(now), sale(now)]), 0, 'same-time credits precede settlement');
console.log('12 wallet balance regression checks passed');
